import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  download,
  readXlsxSheet,
  readZip,
  writeAtomically,
} from './open-data.ts';

// Writes the official reference data of the establishments as an upsert migration, rerun on newer files.
const sources = {
  naf2025:
    'https://www.insee.fr/fr/statistiques/fichier/8617910/Structure%20NAF%202025%20Maj%202024-10-04.xlsx',
  correspondences:
    'https://www.insee.fr/fr/statistiques/fichier/8617910/Correspondances_NAFrev2-NAF2025.xlsx',
  rome: 'https://www.francetravail.org/files/live/sites/peorg/files/documents/Statistiques-et-analyses/Open-data/ROME/261014-rome_arbosecteursnaf-octobre-2026.xlsx',
};
const naf2025Sheet = 'Sous-classes';
const correspondenceSheet = 'NAF rév. 2 vers NAF 2025';
const subClass = /^\d{2}\.\d{2}[A-Z]$/;

export type Workbooks = {
  naf2025: Buffer;
  correspondences: Buffer;
  rome: Buffer;
};

type Activity = {
  nomenclature: 'NAF_REV2' | 'NAF_2025';
  code: string;
  label: string;
};

const romeSheet = 'Secteur NAF 10-2026';

type RomeJobs = {
  /** `[ROME code, title]`, each job once. */
  jobs: [string, string][];
  /** Division NAF (two digits) → indexes in `jobs`. */
  divisions: Record<string, number[]>;
};

export function buildJobs(workbook: Buffer): RomeJobs {
  const rows = readXlsxSheet(readZip(workbook), romeSheet);
  const jobs: [string, string][] = [];
  const indexOf = new Map<string, number>();
  const divisions: Record<string, number[]> = {};
  let division: string | null = null;
  for (const { outline, cells } of rows) {
    if (outline === 0) {
      const code = cells.A?.trim() ?? '';
      // « 0 » is the transverse row: jobs of no division in particular.
      division =
        /^\d+$/.test(code) && Number(code) > 0 ? code.padStart(2, '0') : null;
      continue;
    }
    const code = cells.A?.trim();
    const title = cells.B?.trim();
    if (!division || !code || !title || code === title) continue;
    let index = indexOf.get(code);
    if (index === undefined) {
      index = jobs.push([code, title]) - 1;
      indexOf.set(code, index);
    }
    (divisions[division] ??= []).push(index);
  }
  if (jobs.length === 0) throw new Error('No job read from the sheet.');
  // The map picks a job by its label: the migration would fail on a label given twice.
  const labels = new Set(jobs.map(([, title]) => title));
  if (labels.size < jobs.length)
    throw new Error('Two jobs share the same label in the sheet.');
  return { jobs, divisions };
}

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;

function rows(values: string[][]) {
  return values.map((row) => `    (${row.map(quote).join(', ')})`).join(',\n');
}

function readActivities({ naf2025, correspondences }: Workbooks) {
  const activities: Activity[] = [];
  for (const { cells } of readXlsxSheet(readZip(naf2025), naf2025Sheet)) {
    const code = cells.A?.trim() ?? '';
    if (subClass.test(code))
      activities.push({
        nomenclature: 'NAF_2025',
        code,
        label: cells.B!.trim(),
      });
  }
  const rev2 = new Map<string, string>();
  const links = new Set<string>();
  for (const { cells } of readXlsxSheet(
    readZip(correspondences),
    correspondenceSheet,
  )) {
    const from = cells.A?.trim() ?? '';
    const to = cells.D?.trim() ?? '';
    if (!subClass.test(from) || !subClass.test(to)) continue;
    rev2.set(from, cells.B!.trim());
    links.add(`${from} ${to}`);
  }
  for (const [code, label] of rev2)
    activities.push({ nomenclature: 'NAF_REV2', code, label });
  const known = new Set(
    activities.map(({ nomenclature, code }) => `${nomenclature} ${code}`),
  );
  const correspondenceRows = [...links].map((link) => link.split(' '));
  for (const [, to] of correspondenceRows)
    if (!known.has(`NAF_2025 ${to}`))
      throw new Error(
        `Unknown NAF 2025 subclass in the correspondence: ${to}.`,
      );
  if (rev2.size === 0 || activities.length === rev2.size)
    throw new Error('Incomplete NAF nomenclature.');
  return { activities, correspondences: correspondenceRows };
}

/** The SQL of the official reference data; throws on a file that does not have the expected shape. */
export function buildReferenceSql(workbooks: Workbooks) {
  const { activities, correspondences } = readActivities(workbooks);
  const { jobs, divisions } = buildJobs(workbooks.rome);
  const divisionRows = [
    ...new Set(
      activities.map(
        ({ nomenclature, code }) => `${nomenclature} ${code.slice(0, 2)}`,
      ),
    ),
  ].map((division) => division.split(' '));
  const jobDivisions = Object.entries(divisions).flatMap(
    ([division, indexes]) =>
      indexes.map((index) => [jobs[index]![0], division]),
  );
  const sql = `-- Generated by \`node scripts/reference-data.ts\` from the files of the INSEE and of France Travail
-- (Licence Ouverte): do not edit by hand, generate a new migration from newer files instead.

INSERT INTO reference.naf_divisions (nomenclature, code)
VALUES
${rows(divisionRows)}
ON CONFLICT DO NOTHING;

INSERT INTO reference.naf_activities (nomenclature, code, label)
VALUES
${rows(activities.map(({ nomenclature, code, label }) => [nomenclature, code, label]))}
ON CONFLICT (nomenclature, code) DO UPDATE SET label = EXCLUDED.label;

WITH official (rev2_code, naf2025_code) AS (
    VALUES
${rows(correspondences)}
), removed AS (
    DELETE FROM reference.naf_correspondences c
    WHERE NOT EXISTS (
        SELECT 1 FROM official o
        WHERE o.rev2_code = c.rev2_code AND o.naf2025_code = c.naf2025_code
    )
)
INSERT INTO reference.naf_correspondences (rev2_code, naf2025_code)
SELECT rev2_code, naf2025_code FROM official
ON CONFLICT DO NOTHING;

INSERT INTO reference.jobs (rome_code, label)
VALUES
${rows(jobs)}
ON CONFLICT (rome_code) DO UPDATE SET label = EXCLUDED.label;

WITH official (rome_code, division) AS (
    VALUES
${rows(jobDivisions)}
), removed AS (
    DELETE FROM reference.job_divisions j
    WHERE NOT EXISTS (
        SELECT 1 FROM official o
        WHERE o.rome_code = j.rome_code AND o.division = j.division
    )
)
INSERT INTO reference.job_divisions (rome_code, division)
SELECT rome_code, division FROM official
ON CONFLICT DO NOTHING;

REFRESH MATERIALIZED VIEW reference.job_activities;
ANALYZE reference.naf_divisions, reference.naf_activities, reference.naf_correspondences,
    reference.jobs, reference.job_divisions, reference.job_activities;
`;
  return {
    sql,
    counts: {
      activities: activities.length,
      correspondences: correspondences.length,
      jobs: jobs.length,
      jobDivisions: jobDivisions.length,
    },
  };
}

export async function generate(
  path: string,
  fetchWorkbook: (url: string) => Promise<Buffer> = download,
) {
  const [naf2025, correspondences, rome] = await Promise.all(
    [sources.naf2025, sources.correspondences, sources.rome].map((url) =>
      fetchWorkbook(url),
    ),
  );
  const { sql, counts } = buildReferenceSql({
    naf2025: naf2025!,
    correspondences: correspondences!,
    rome: rome!,
  });
  await writeAtomically(path, sql);
  return counts;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const path = process.argv[2];
  if (!path) {
    console.error(
      'Usage: node scripts/reference-data.ts backend/src/main/resources/db/migration/V<n>__reference_data_official.sql',
    );
    process.exitCode = 1;
  } else {
    try {
      const counts = await generate(resolve(path));
      console.log(
        `${counts.activities} NAF subclasses, ${counts.correspondences} correspondences, ${counts.jobs} jobs and ${counts.jobDivisions} job divisions written to ${path}.`,
      );
    } catch (error) {
      console.error(error);
      process.exitCode = 1;
    }
  }
}
