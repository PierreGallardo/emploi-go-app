import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

// A script without `src`: its hash covers exactly the text between its tags.
const inlineScript = /<script\b(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/gi;

/** The `'sha256-…'` sources of the inline scripts of one HTML page. */
export function inlineScriptHashes(html: string) {
  return [...html.matchAll(inlineScript)].map(
    ([, body = '']) =>
      `'sha256-${createHash('sha256').update(body).digest('base64')}'`,
  );
}

/** One policy for every page: the inline scripts that React Router writes are allowed by their hashes, nothing else inline. */
export function contentSecurityPolicy(pages: string[]) {
  const hashes = [...new Set(pages.flatMap(inlineScriptHashes))].sort();
  return [
    "default-src 'self'",
    ["script-src 'self'", ...hashes].join(' '),
    "style-src 'self'",
    // Radix dialogs (react-remove-scroll) and input-otp insert <style> elements whose rules vary at runtime: no hash can match them.
    "style-src-elem 'self' 'unsafe-inline'",
    // React and MapLibre set styles through the CSSOM, which no directive restricts: a style attribute in the markup is never needed.
    "style-src-attr 'none'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** The policy of the HTML pages of a client build, prerendered pages and SPA fallback included. */
export async function buildPolicy(clientDirectory: string) {
  const files = await readdir(clientDirectory, { recursive: true });
  const pages = await Promise.all(
    files
      .filter((file) => file.endsWith('.html'))
      .map((file) => readFile(join(clientDirectory, file), 'utf8')),
  );
  if (pages.length === 0)
    throw new Error(`No HTML page in ${clientDirectory}.`);
  return contentSecurityPolicy(pages);
}

/** The header line that the Caddyfile imports, written next to the client build. */
export async function writeCaddyPolicy(clientDirectory: string, file: string) {
  const policy = await buildPolicy(clientDirectory);
  await writeFile(
    file,
    `# Generated by the build from its HTML pages: never edit it.\nContent-Security-Policy "${policy}"\n`,
  );
}
